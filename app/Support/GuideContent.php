    /** @return array{slug:string,title:string,icon:string,items:array<int,array{q:string,a:string}>}|null */
    public static function categoryBySlug(?string $slug): ?array
    {
        if ($slug === null || $slug === '') {
            return null;
        }

        foreach (self::categories() as $category) {
            if ($category['slug'] === $slug) {
                return $category;
            }
        }

        return null;
    }
