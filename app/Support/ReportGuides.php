 * Налаштування → «Пам'ятки для звітів»; порожнє поле — показується
 * дефолтний текст нижче, а не порожнє вікно.
 */
class ReportGuides
{
    /** @var array<string,string> */
    private const DEFAULTS = [
        'bizwar' => "Що писати:\n".
            "• Дата бою — саме день, коли він відбувся, а не день подачі звіту.\n".
            "• Кількість перемог і поразок за цей бій.\n".
            "• Час(и) капта, у яких брали участь — можна кілька, якщо звітуєте за декілька заходів одразу.\n\n".
            "Які скріни додати:\n".
            "• Скріншот результату бою (де видно рахунок W/L).\n".
            "• Скрін повідомлення в чаті про результат бізнес-війни: «Сім'я [РОДИНА-ПЕРЕМОЖЕЦЬ] відстояла/захопила бізнес [назва] у сім'ї [РОДИНА-ПЕРЕМОЖЕНА]». Першою в цьому повідомленні завжди йде родина-переможець, другою — переможена — звірте перемогу/поразку саме за цим порядком, а не навпаки.\n".
            "• Якщо є розбіжність з підсумком інших учасників — краще додати ще один скрін, де чітко видно дату й час.",
        'contract' => "Що писати:\n".
            "• Дата виконання контрактів.\n".
            "• Кількість за кожною вагою окремо: легкий / середній / тяжкий.\n\n".
            "Які скріни додати:\n".
            "• Скрін підтвердження виконання кожного контракту (або спільний скрін, якщо гра показує їх списком).\n".
            "• Дата на скрінах має збігатись із вказаною датою звіту.",
        'investment' => "Що писати:\n".
            "• Точну суму інвестиції.\n\n".
            "Які скріни додати:\n".
            "• Скрін підтвердження транзакції/вкладення із сумою, яка чітко видна.",
        'other' => "Опишіть словами, що саме звітуєте, і додайте скрін(и), які підтверджують написане — чим детальніше опис, тим швидше модератор розгляне звіт.",
    ];

    public static function text(string $type): ?string
    {
        $custom = trim((string) Setting::get("report_guide_{$type}"));

        return $custom !== '' ? $custom : (self::DEFAULTS[$type] ?? null);
    }

    /** @return array<string,string|null> */
    public static function all(): array
    {
        return [
            'bizwar' => self::text('bizwar'),
            'contract' => self::text('contract'),
            'investment' => self::text('investment'),
            'other' => self::text('other'),
        ];
    }
}
